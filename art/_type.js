const ADV={'.':22,',':22,"'":18,'-':38,':':22};
function textPath(str,tr){
  let x=0, subs=[];
  for(const ch of String(str).toUpperCase()){
    if(ch===' '){ x+=30+tr; continue; }
    const gl=GL[ch]; if(!gl){ x+=30+tr; continue; }
    let mx=0;
    gl.forEach(poly=>{ subs.push(poly.map((pt,i)=>(i?'L':'M')+(pt[0]+x)+' '+pt[1]).join(' ')+' Z');
      poly.forEach(pt=>mx=Math.max(mx,pt[0])); });
    x += (ADV[ch]||mx+12) + tr;
  }
  return {d:subs.join(' '), w:x-12-tr};
}
